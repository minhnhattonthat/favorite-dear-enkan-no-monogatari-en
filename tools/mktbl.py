"""mktbl.py: write tbl/jp.tbl for Enkan no Monogatari from game 1's hand-checked table plus a font match.

    python -X utf8 tools/mktbl.py [--g1 ../favorite-dear-en/tbl/jp.tbl] [--g1exe ../favorite-dear-en/work/disc/tree/PSX.EXE]

Codes are 16-bit LE font cells (`2400=あ` is code 0x0024), same layout as game 1 (docs/re/text.md §Encoding):
- a cell whose 12x12 bitmap equals game 1's cell (all kanji 0x0BE-0x57C, most of 0x5EA-0x66B) takes game 1's
  character;
- punctuation, kana and Latin were redrawn but keep game 1's layout, so 0x000-0x0BD and 0x57B-0x5B3 take game 1's
  character too (checked on the labelled sheet work/recon/font.png);
- every other non-blank cell (0x5B4-0x5CB, changed or new cells 0x5E8-0x6EF) takes fontmatch.py's best MS Gothic
  match, with the cells fixed by eye in FIX.
Game 1's ②③④ (0x5B4 0x5BF 0x5CC) and ￥ (0x5E8) are gone here. Run once; the table is then a hand-edited source.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from font import glyph  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
G1 = ROOT.parent / "favorite-dear-en"
NCODES = 0x6F0
LAYOUT = [(0x000, 0x0BD), (0x57B, 0x5B3), (0x5CD, 0x5E0)]  # same characters as game 1, glyphs redrawn
# cells checked by eye on work/recon/fontmatch.png where the MS Gothic match was weak or wrong
FIX = {0x68C: "揃"}  # MS Gothic match said 犠 (0.835); the cell is 揃
BLANK = {0x5E9: "〿"}  # empty cell between 湾 and 史, used as a space in game 1


def load_g1(path):
    head, m = [], {}
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        if len(k) == 4 and k[2:] != "FF":
            m[int(k[2:] + k[:2], 16)] = v
        else:
            head.append(line)
    return head, m


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--g1", default=str(G1 / "tbl/jp.tbl"))
    ap.add_argument("--g1exe", default=str(G1 / "work/disc/tree/PSX.EXE"))
    ap.add_argument("--exe", default=str(ROOT / "work/disc/tree/PSX.EXE"))
    ap.add_argument("--out", default=str(ROOT / "tbl/jp.tbl"))
    a = ap.parse_args()
    from fontmatch import match
    exe = Path(a.exe).read_bytes()
    g1exe = Path(a.g1exe).read_bytes()
    ctrl, g1 = load_g1(a.g1)
    _, res = match(exe)
    m, src = {}, {"g1-same": 0, "g1-layout": 0, "match": 0, "fix": 0}
    for c, ch, score, *_ in res:
        same = c < 0x66C and glyph(g1exe, c, 0x1213C0, msb=False) == glyph(exe, c)
        if c in BLANK:
            m[c] = BLANK[c]
        elif not ch and c != 0:
            continue  # blank cell
        elif c in FIX:
            m[c], src["fix"] = FIX[c], src["fix"] + 1
        elif same and c in g1:
            m[c], src["g1-same"] = g1[c], src["g1-same"] + 1
        elif any(lo <= c <= hi for lo, hi in LAYOUT) and c in g1:
            m[c], src["g1-layout"] = g1[c], src["g1-layout"] + 1
        else:
            m[c], src["match"] = ch, src["match"] + 1
    vals = list(m.values())
    dup = sorted({v for v in vals if vals.count(v) > 1})
    if dup:
        sys.exit(f"duplicate characters: {dup} at " + ", ".join(f"{c:#x}" for c in m if m[c] in dup))
    lines = ["# Favorite Dear: Enkan no Monogatari: 16-bit LE font-cell codes (key bytes = code low, high).",
             "# Generated by tools/mktbl.py from game 1's table (../favorite-dear-en/tbl/jp.tbl) + fontmatch, then",
             "# hand-edited. 0x001-0x014 duplicate 0x5CD-0x5E0 and decode as stand-ins (､｡･ etc.), as in game 1.",
             "# Control codes: game 1's printer set (verified for this game in docs/re/text.md)."] + ctrl
    for c in sorted(m):
        lines.append(f"{c & 0xFF:02X}{c >> 8:02X}={m[c]}")
    Path(a.out).parent.mkdir(exist_ok=True)
    Path(a.out).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(len(m), "codes", src)


if __name__ == "__main__":
    main()
